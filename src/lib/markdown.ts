import { site } from '../data/site';

/** The whole portfolio as clean Markdown. Used by /portfolio.md. */
export function toMarkdown(base: URL): string {
  const abs = (path: string) => new URL(path, base).href;
  const lines: string[] = [
    `# ${site.name}`,
    '',
    `> ${site.roleLine}`,
    '',
    `- Website: ${abs('/')}`,
    `- Email: ${site.email}`,
    `- GitHub: ${site.links.github}`,
    `- LinkedIn: ${site.links.linkedin}`,
    '',
    '## About',
    '',
    ...site.about.flatMap((p) => [p, '']),
    site.availability,
    '',
    '## Education',
    '',
    ...site.education.map((e) => `- **${e.school}**: ${e.detail}${e.when ? ` (${e.when})` : ''}`),
    '',
    '## Experience',
    '',
    ...site.experience.flatMap((x) => [
      `### ${x.role}, ${x.org}${x.when ? ` (${x.when})` : ''}`,
      '',
      ...x.points.map((pt) => `- ${pt}`),
      '',
    ]),
    '## Featured projects',
    '',
    ...site.projects.flatMap((p) => [
      `### ${p.name}`,
      '',
      `Page: ${abs(`/projects/${p.slug}`)}`,
      '',
      p.oneLine,
      '',
      ...p.body.flatMap((para) => [para, '']),
      ...p.facts.map((f) => `- ${f.label}: ${f.value}`),
      ...p.links.map((l) => `- ${l.label}: ${l.href}`),
      '',
    ]),
    '## Other projects',
    '',
    ...site.otherProjects.map((name) => `- ${name}`),
    '',
    '## Recognition',
    '',
    ...site.recognition.map((r) => `- ${r}`),
    '',
    '## Skills',
    '',
    `- Languages: ${site.skills.languages.join(', ')}`,
    `- Areas: ${site.skills.areas.join(', ')}`,
    `- ML libraries: ${site.skills.ml.join(', ')}`,
    `- Tools: ${site.skills.tools.join(', ')}`,
    `- Spoken languages: ${site.spoken.join(', ')}`,
    '',
    '## Interests',
    '',
    ...site.interests.map((i) => `- ${i}`),
    '',
    '## Contact',
    '',
    `Email ${site.email}. GitHub ${site.links.github}. LinkedIn ${site.links.linkedin}.`,
    '',
  ];
  return lines.join('\n');
}
